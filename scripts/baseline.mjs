/**
 * Generate docs/milestone/BASELINE.md from the repository at the accepted
 * baseline commit. Nothing is typed by hand: addresses come from
 * artifacts/deployment.json, files from `git ls-tree`, sizes from `git cat-file`.
 *
 * Usage: node scripts/baseline.mjs
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { REPO_ROOT } from "./_shared.mjs";

const BASE = "b903f94";
const git = (...args) => execFileSync("git", args, { cwd: REPO_ROOT, encoding: "utf8" }).trim();

const commit = git("log", "-1", "--format=%H %an <%ae> %ad", "--date=iso", BASE);
const deployment = JSON.parse(git("show", `${BASE}:artifacts/deployment.json`));
const files = git("ls-tree", "-r", "--long", BASE)
  .split("\n")
  .map((line) => {
    const m = /^\d+ blob [0-9a-f]+\s+(\d+)\t(.+)$/.exec(line);
    return m ? { size: Number(m[1]), path: m[2] } : null;
  })
  .filter(Boolean);

const group = (prefix) => files.filter((f) => f.path.startsWith(prefix));
const table = (list) => list.map((f) => `| \`${f.path}\` | ${f.size} |`).join("\n");

const lines = (path_) => git("show", `${BASE}:${path_}`).split("\n").length;

const md = `# Baseline record

Generated by \`node scripts/baseline.mjs\`. Do not edit by hand.

Every claim in the milestone is a delta from this commit.

- Accepted baseline: \`${commit}\`
- Network: ${deployment.network}, chain ${deployment.chainId}
- RPC: ${deployment.rpc}
- Deployer: \`${deployment.deployer}\`
- Runner: \`${deployment.runner}\`
- Deployed at: ${deployment.deployedAt}

## v0 contract addresses

| Contract | Address | Deploy transaction |
| --- | --- | --- |
${Object.entries(deployment.addresses)
  .map(([k, v]) => `| ${k} | \`${v}\` | \`${deployment.transactions[k] ?? ""}\` |`)
  .join("\n")}

Whether these still answer is measured in \`docs/evidence/milestone/v0-liveness.json\`
(Studio-dev may have reset since the baseline).

## v0 contract sources (preserved, never rewritten)

| File | Lines at baseline |
| --- | --- |
${group("contracts/").map((f) => `| \`${f.path}\` | ${lines(f.path)} |`).join("\n")}

## v0 evidence (preserved, becomes the comparison arm)

| File | Bytes |
| --- | --- |
${table(group("docs/evidence/"))}
${table(group("artifacts/"))}

## File-level inventory by area

| Area | Files |
| --- | --- |
${["app", "components", "lib", "scripts", "tests", "docs", "contracts", "public"]
  .map((area) => `| \`${area}/\` | ${group(area + "/").length} |`)
  .join("\n")}

## Known defects carried into the milestone

The ten corrections C1 to C10 are listed with file references in
\`docs/milestone/DELTA.md\`.
`;

mkdirSync(path.join(REPO_ROOT, "docs", "milestone"), { recursive: true });
writeFileSync(path.join(REPO_ROOT, "docs", "milestone", "BASELINE.md"), md);
console.log("wrote docs/milestone/BASELINE.md");
