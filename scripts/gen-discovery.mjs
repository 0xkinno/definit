/**
 * Generate the Phase 0 / 0B documents from recorded evidence.
 *
 *   docs/milestone/NETWORK_DECISION.md
 *   docs/milestone/DISCOVERY_V1.md
 *   docs/milestone/GATE.md
 *   docs/milestone/FINDING.md   (the E6 write-up, interim form; Phase 4 extends it)
 *
 * Every number and every tick comes from a file under docs/evidence/milestone/.
 * A tick is only written when its evidence exists and satisfies its predicate;
 * otherwise the box stays empty and says why.
 *
 * Usage: node scripts/gen-discovery.mjs
 */

import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

import { REPO_ROOT } from "./_shared.mjs";

const EV = path.join(REPO_ROOT, "docs", "evidence", "milestone");
const SPIKE = path.join(EV, "spike");
const DOCS = path.join(REPO_ROOT, "docs", "milestone");
mkdirSync(DOCS, { recursive: true });
const rel = (p) => path.relative(REPO_ROOT, p).replace(/\\/g, "/");
const rd = (p) => JSON.parse(readFileSync(p, "utf8"));
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

const matrix = rd(path.join(EV, "network-matrix.json"));
const liveness = rd(path.join(EV, "v0-liveness.json"));
const repros = readdirSync(SPIKE, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name.startsWith("repro-") && existsSync(path.join(SPIKE, d.name, "summary.json")))
  .map((d) => ({ dir: `${rel(SPIKE)}/${d.name}`, summary: rd(path.join(SPIKE, d.name, "summary.json")) }));
const dev = matrix.networks["studio-dev"];

// ---------------------------------------------------------------- ad hoc spike records
const adhoc = (name) => (existsSync(path.join(SPIKE, name)) ? rd(path.join(SPIKE, name)) : null);
const e2 = adhoc("run-e2a.json");
const e4b = adhoc("run-e4b.json");
const e4fund = ["run-e4u.json"].map(adhoc);
const e6run1 = adhoc("e6-h1-v0-run1.json");
const e6run2 = adhoc("e6-h1-v0-run2.json");
const e5adhoc = adhoc("e5-direct-e5.json");

const lifecycleTransitions = (r) => {
  let last = "";
  const out = [];
  for (const s of r.samples) {
    const l = s.lifecycle;
    const k = `${l.projectedStatus ?? "?"}${l.resolutionAction && l.resolutionAction !== "NoOp" ? "/" + l.resolutionAction : ""}`;
    if (k !== last) out.push(`${((s.atMs - r.submittedAtMs) / 1000).toFixed(0)}s ${k}`);
    last = k;
  }
  return out.join(" | ");
};

const winners = repros.filter((r) => r.summary.E1.pass && r.summary.E5.pass);
const e1Everywhere = repros.length > 0 && repros.every((r) => r.summary.E1.pass);
const e6Anywhere = repros.some((r) => r.summary.E6.observed) || (e6run2?.result?.settleExecutedWithReturn && e6run2?.result?.settleDecidedBeforePromotionAppealDeadline);

// ------------------------------------------------------------ NETWORK_DECISION.md
const row = (k) => {
  const n = matrix.networks[k];
  const cell = (v) => (typeof v === "string" ? v.replace(/^not measured: /, "not measured: ").slice(0, 70) : JSON.stringify(v));
  return `| ${n.network} | ${n.chainId} | ${n.lifecycleMethodAnswers} | ${typeof n.feeSurface?.gasless === "string" ? "not determined" : n.feeSurface?.gasless} | ${typeof n.runnerAccepted === "boolean" ? n.runnerAccepted : "not measured"} | ${typeof n.executesContracts === "boolean" ? n.executesContracts : "not measured"} |`;
};

const bradburyRule = {
  accepts: matrix.networks.bradbury.executesContracts === true,
  lifecycle: matrix.networks.bradbury.lifecycleMethodAnswers === true,
};
const studionetUsable = matrix.networks.studionet.executesContracts === true;
const chosen = !bradburyRule.accepts || !bradburyRule.lifecycle ? (studionetUsable ? "studionet" : "studio-dev") : "bradbury";

writeFileSync(
  path.join(DOCS, "NETWORK_DECISION.md"),
  `# Network decision

Generated by \`node scripts/gen-discovery.mjs\` from \`docs/evidence/milestone/network-matrix.json\`
(probe: \`npm run probe:network\`). Do not edit by hand.

## The rule

Bradbury if it accepts the v0.6 toolchain, answers lifecycle reads and delivers
finalized messages. Otherwise Studionet. Otherwise Studio-dev, with the reset
risk stated in LIMITATIONS.

## What was measured

| Network | Chain id | Lifecycle method answers | Gasless (from the estimate) | Runner accepted | Executes contracts |
| --- | --- | --- | --- | --- | --- |
${["studio-dev", "studionet", "bradbury", "asimov"].map(row).join("\n")}

Bradbury and Asimov were reachable but could not be measured further: the probe
account holds ${matrix.networks.bradbury.probeAccountBalanceGen} GEN there and neither exposes \`sim_fundAccount\`, so funding needs an external
faucet. That is an action the operator must take. Their lifecycle method is
reported as not answering on the public RPC host that was probed.

Studionet answered RPC but did not execute the probe contract
(${matrix.networks.studionet.probeDeploy?.consensusResult ?? "see matrix"}), so it cannot host DEFINIT today.

## Decision

**${chosen === "studio-dev" ? "Studio-dev (chain " + dev.chainId + ")" : chosen}.**

- Bradbury fails the first rule: its lifecycle method does not answer on the probed host and it could not be funded, so it cannot deliver evidence for invariant I8.
- Studionet fails the second: it does not execute contracts.
- Studio-dev executes contracts with the pinned runner, answers \`gen_getTransactionLifecycle\`, and
  delivered the finalized-stage message in ${dev.finalizedMessageDelivery?.delivered ?? "n/a"} of ${dev.finalizedMessageDelivery?.of ?? "n/a"} recorded runs.

Observed on Studio-dev: appeal window ${dev.appealWindowSeconds} seconds; the finalized child transaction was created
${dev.finalizedMessageDelivery?.childCreatedSecondsAfterAppealDeadline} second(s) after the appeal deadline (median of the recorded runs).

## Risk carried

Studio-dev is a release-candidate preview. It may reset. The v0 contracts from
the accepted baseline were probed on ${liveness.checkedAt}: ${liveness.allAnswer ? "all three still answer" : "at least one no longer answers"}
(\`docs/evidence/milestone/v0-liveness.json\`). Studio-dev also rate-limits at 500 requests
per hour for a funded account, which shapes how experiments are paced.

If the operator funds an account on Bradbury and the lifecycle method becomes
available there, rerun \`npm run probe:network\`. This document regenerates.
`,
);

// ---------------------------------------------------------------- DISCOVERY_V1.md
const e1runs = repros.flatMap((r) => r.summary.E1.runs.map((x) => ({ ...x, dir: r.dir })));
const afterDeadline = e1runs.filter((x) => typeof x.childCreatedSecondsAfterAppealDeadline === "number").map((x) => x.childCreatedSecondsAfterAppealDeadline);
const windows = e1runs.map((x) => x.appealWindowSeconds);
const e6 = e6run2?.result;

const parts = [];
parts.push(`# Discovery record: DEFINIT v1

Generated by \`node scripts/gen-discovery.mjs\`. Numbers come from the raw records named
in each item; where a record does not exist the item says UNKNOWN.

## 1. Sponsor primitive

Stage-bound internal messages (\`emit(on='finalized')\`) and the protocol lifecycle
projection (\`gen_getTransactionLifecycle\`). A message pinned to the finalized
stage is not a call the emitting contract makes. It is a child transaction the
protocol creates, from the deciding transaction, after that transaction survives
its appeal window.

## 2. Observed constraint

Three measurements, all on ${dev.network} (chain ${dev.chainId}):

- **E1 delivery timing.** ${e1runs.length} recorded decision(s) across ${repros.length} full reproduction(s). In each, the finalized message arrived as a child transaction triggered by the deciding transaction, created ${afterDeadline.length ? `${Math.min(...afterDeadline)} to ${Math.max(...afterDeadline)} second(s) after the appeal deadline (median ${median(afterDeadline)})` : "UNKNOWN"}. The appeal window was ${windows.length ? `${median(windows)} second(s)` : "UNKNOWN"}. Evidence: ${repros.map((r) => `\`${r.dir}/summary.json\``).join(", ") || "none"}.
- **E5 sender truth.** The sink recorded the emitting contract's address as the sender of every delivered message and the externally owned account's address for a direct call. Evidence: ${repros.map((r) => `\`${r.dir}/e5-direct-e5.json\``).join(", ") || "none"}.
- **E6 v0 differential.** ${e6 ? `v0's vault accepted the funder's \`settle\` (execution ${e6run2.settle.execution}, vault status ${e6run2.vaultReceipt.status}) while the promotion transaction's lifecycle read ${e6.promotionLifecycleWhenSettleSubmitted.projectedStatus} with resolutionAction ${e6.promotionLifecycleWhenSettleSubmitted.resolutionAction}. The settle was decided at ${e6.settleMaterializedAt}, ${e6.promotionAppealDeadline - e6.settleMaterializedAt} second(s) before the promotion's appeal deadline (${e6.promotionAppealDeadline}).` : "UNKNOWN"} Evidence: \`${rel(path.join(SPIKE, "e6-h1-v0-run2.json"))}\`.

## 3. Evidence

| Record | Path |
| --- | --- |
${repros.map((r) => `| Full reproduction | \`${r.dir}/\` |`).join("\n")}
| E2 appeal inside the window | \`${rel(path.join(SPIKE, "run-e2a.json"))}\` |
| E4 gross underfunding | rejected at submission, see \`findings-session1.json\` and the E4 note below |
| E4b failing finalized child | \`${rel(path.join(SPIKE, "run-e4b.json"))}\` |
| E6 differential | \`${rel(path.join(SPIKE, "e6-h1-v0-run1.json"))}\`, \`${rel(path.join(SPIKE, "e6-h1-v0-run2.json"))}\` |
| Network matrix | \`${rel(path.join(EV, "network-matrix.json"))}\` |

Additional measured facts that shape the build:

${e2 ? `- **E2 appeal.** Appealing inside the window created a new decision (decisionId changed from ${e2.samples.find((s) => s.lifecycle.decisionId)?.lifecycle.decisionId ?? "?"} to ${[...e2.samples].reverse().find((s) => s.lifecycle.decisionId)?.lifecycle.decisionId ?? "?"}). Lifecycle: ${lifecycleTransitions(e2)}. The finalized message was created at ${e2.children[0]?.created_timestamp} against a final appeal deadline of ${e2.finalTx.latestDecision.appealDeadline}. This run does not show the window being extended; that is stated plainly rather than inferred.` : "- E2: UNKNOWN (no record)."}
- **E3 accepted-stage repetition.** UNKNOWN. \`emit(on='accepted')\` raised an execution error in the VM under the pinned runner, with and without a value argument (observation O5 in \`findings-session1.json\`), so repeated accepted-stage delivery could not be observed. The docs say it can repeat; this record neither confirms nor denies it.
- **E4 underfunding.** A child budget below the network's minimum was rejected at submission with \`AllocationLifecycleBudgetInsufficient\` for each budget tried, so gross underfunding cannot lock value in. A funded child that fails at execution is different: ${e4b ? `the parent ended ${e4b.finalTx.status} / ${e4b.finalTx.txExecutionResultName}, the child ended ${e4b.children[0]?.status} / ${e4b.children[0]?.txExecutionResultName}, and the sink recorded ${e4b.sink.filter((x) => x.tag.startsWith("e4b")).length} entries` : "UNKNOWN"}. The parent succeeds and the effect is not applied.
- **C6.** A transaction that ended FINISHED_WITH_ERROR still reached Finalized (see \`findings-session1.json\`, O3).
- **Fee allocations.** Each emitted message needs one allocation keyed by recipient and target method name. Two messages to the same method collide (\`AllocationDuplicateKey\`), so the two stages must target different methods.

## 4. Why existing approaches do not solve it

- **Status polling.** Accepted and Finalized are different protocol states, and a successful status is not a successful execution (O3).
- **Final-scope reads.** Measured in v0 and recorded in \`docs/LIMITATIONS.md\`: the in-VM final-scoped read never returns, and the client-scoped one resolves against transaction finality.
- **Fixed timers.** v0's 120 second constant has no relationship to the protocol window (${windows.length ? `${median(windows)} second(s) here` : "UNKNOWN"}), and an appeal creates a new decision with its own deadline.
- **v0 itself.** E6: its vault accepted a release against a decision that was still appealable.

## 5. New capability

Payment authority that cannot exist before finality. The release instruction is
a protocol delivery from the deciding transaction. No reader, timer, caller or
agent can produce it early.

## 6. One invariant

**I1 Delivery.** Value leaves the vault only inside a transaction whose
\`sender_address\` is the bound gate and which was created by an \`on='finalized'\`
emission.

## 7. One failure mode

**Stranded value (E4b).** Moving authority onto delivery creates a failure v0 did not
have: if the finalized child fails or never arrives, the escrow has no path out.
Closed by I9 to I11: a clock may only return value to the funder, never release it.

## 8. One reproducible demonstration

\`npm run spike\` reproduces E1, E5 and E6 from scratch and writes a generated
summary. It has been run ${repros.length} time(s); each run is under
\`docs/evidence/milestone/spike/repro-*/\`.
`);
writeFileSync(path.join(DOCS, "DISCOVERY_V1.md"), parts.join("\n"));

// ---------------------------------------------------------------- GATE.md
const need = (p) => existsSync(path.join(REPO_ROOT, p));
const tick = (ok, text, evidence) => `- [${ok ? "x" : " "}] ${text}\n  - evidence: ${evidence}`;
const gate = [
  tick(e1Everywhere && e6Anywhere, "We discovered something non-obvious (E1 plus E6)", repros.length ? `${repros.map((r) => `\`${r.dir}/summary.json\``).join(", ")}, \`${rel(path.join(SPIKE, "e6-h1-v0-run2.json"))}\`` : "missing"),
  tick(winners.length >= 2, `We reproduced it ourselves (\`npm run spike\` run twice, both recorded; ${winners.length} of ${repros.length} runs pass E1 and E5)`, repros.map((r) => `\`${r.dir}/summary.json\``).join(", ") || "missing"),
  tick(e1Everywhere, "v1 exists because of that discovery (the thesis sentence traces to E1)", e1Everywhere ? `E1 passes in every recorded reproduction: ${repros.map((r) => `\`${r.dir}\``).join(", ")}` : "E1 not passing everywhere"),
  tick(need("docs/milestone/FAULT_MATRIX.md"), "We know exactly how we will break it (the fault matrix is written)", "`docs/milestone/FAULT_MATRIX.md`"),
  tick(need("docs/milestone/PROOF_V1.md"), "We know exactly how we will prove it survived (the counterfactual design is written)", "`docs/milestone/PROOF_V1.md`"),
];
const passed = gate.every((g) => g.startsWith("- [x]"));
writeFileSync(
  path.join(DOCS, "GATE.md"),
  `# Discovery gate

Generated by \`node scripts/gen-discovery.mjs\`. A box is ticked only when the named
evidence exists and satisfies its predicate. No Phase 1 code is written until every
box is ticked.

${gate.join("\n")}

**Gate: ${passed ? "PASSED" : "NOT PASSED"}.**
`,
);

// ---------------------------------------------------------------- FINDING.md (interim)
writeFileSync(
  path.join(DOCS, "FINDING.md"),
  `# Finding: v0 released against a decision that was still appealable

Generated by \`node scripts/gen-discovery.mjs\`. Phase 4 adds the v1 side of the comparison.

## Method

v0 is deployed unchanged from commit b903f94. One action is driven through
adjudication and escrow. After v0's own 120 second window, the decision contract
is asked to promote the decision. While the promotion transaction's own lifecycle
still reads Accepted (not yet finalizable), the funder calls the vault's \`settle\`.

## Raw timeline

${e6 ? `- promotion transaction lifecycle at the moment the settle was sent: ${e6.promotionLifecycleWhenSettleSubmitted.projectedStatus}, resolutionAction ${e6.promotionLifecycleWhenSettleSubmitted.resolutionAction}
- promotion appeal deadline (protocol): ${e6.promotionAppealDeadline}
- settle decided at: ${e6.settleMaterializedAt}
- settle execution result: ${e6run2.settle.execution}
- vault receipt status: ${e6run2.vaultReceipt.status}
- the settle was decided ${e6.promotionAppealDeadline - e6.settleMaterializedAt} second(s) before the promotion's appeal deadline` : "UNKNOWN: the record is missing."}

Raw records: \`${rel(path.join(SPIKE, "e6-h1-v0-run1.json"))}\` (the first run, in which the simulation of settle failed and no settle was sent; the vault was released by v0's own gate message after promotion finality) and \`${rel(path.join(SPIKE, "e6-h1-v0-run2.json"))}\`.

## Interpretation

The v0 vault accepted a release request from the funder while the decision it read
was still inside its protocol appeal window. That is the gap the milestone sets out
to close.

## What this does and does not prove

It shows the v0 design permitted a release before protocol finality of the thing it
depended on. It does not show an appeal overturning the decision: no overturn was
engineered or observed, and none is claimed. Whether such a release could later be
unwound by a recomputation (hypothesis H1) is not tested here. The v0 vault's own
transfer is emitted on the finalized stage of the settle transaction, which in this
run finalized after the promotion window closed. The finding is about authority, not
about a loss.
`,
);
console.log(`NETWORK_DECISION, DISCOVERY_V1, GATE, FINDING written. Gate ${passed ? "PASSED" : "NOT PASSED"}; reproductions recorded: ${repros.length}`);
